import assert from 'node:assert/strict';
globalThis.window=new EventTarget();
const storage=new Map();globalThis.sessionStorage={setItem:(k,v)=>storage.set(k,v)};
let expired=0;window.addEventListener('session-expired',()=>expired++);
const {api}=await import('./frontend/src/api.js');
let release;
globalThis.fetch=()=>new Promise(resolve=>{release=resolve;});
const oldRequest=api('/notifications').catch(e=>e);
globalThis.fetch=async()=>new Response(JSON.stringify({user:{name:'Admin'}}),{status:200});
await api('/auth/login',{method:'POST',body:{}});
release(new Response('{}',{status:401}));
assert.equal((await oldRequest).status,401);assert.equal(expired,0,'Stale request must not log out a new session');
globalThis.fetch=async()=>new Response('{}',{status:401});
await assert.rejects(api('/notifications'),e=>e.status===401);assert.equal(expired,1);
await assert.rejects(api('/me'),e=>e.status===401);assert.equal(expired,1,'Initial anonymous restore is not session expiry');
globalThis.fetch=async()=>new Response(JSON.stringify({message:'Validation failed'}),{status:400});
await assert.rejects(api('/mail/mailboxes',{method:'POST'}),/Validation failed/);
globalThis.fetch=async()=>{throw new TypeError('offline');};
await assert.rejects(api('/me'),/reach the server/);
globalThis.fetch=async(_url,opts)=>{assert.equal(opts.credentials,'same-origin');return new Response(null,{status:204});};
assert.equal(await api('/auth/logout',{method:'POST'}),null);
console.log('PASS: API client stale-session response, expiry, anonymous restore, validation, offline and cookie/logout checks.');
